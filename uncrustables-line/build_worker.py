#!/usr/bin/env python3
"""Uncrustables line - build the PRIVATE-APP server from the animated GIF.

The Glance SCROLL private-app feature shows ONE still PNG (192x32) and re-fetches
it at the refresh interval you pick in the Glance Setup app (GDN apps are still
frames too; per-frame animation is "not yet" on the Glance roadmap). So the GIF
can't play on the panel as a GIF. The closest thing that works: serve one
keyframe per refresh, so the line advances one beat each time the panel
re-fetches. Ten beats = one full batch, exactly the GIF's storyboard.

This script pulls the keyframes straight out of uncrustables-line.gif (so they
match the GIF pixel for pixel), writes them to worker/frames/, and generates
worker/_worker.js with the PNGs embedded - a single-file Cloudflare Pages
worker with no dependencies. serve.py reads the same worker/frames/ folder.

Run with the repo venv python (needs Pillow):
  "../../glance-dev-network/.venv/bin/python" build_worker.py [path/to/uncrustables-line.gif]
"""
import base64
import io
import sys
from pathlib import Path
from PIL import Image

HERE = Path(__file__).parent
GIF = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parent / "uncrustables-line.gif"
WORKER_DIR = HERE / "worker"
FRAMES_DIR = WORKER_DIR / "frames"

# GIF frame index -> what the beat shows (indices from the 58-frame GIF).
KEYFRAMES = [
    (0,  "empty breads waiting on the belt"),
    (8,  "PB bar #1 down, squirting"),
    (13, "PB #1 done, bar retracting"),
    (22, "jelly bar down, squirting"),
    (28, "jelly done, bar gone"),
    (34, "PB bar #2 down, squirting"),
    (38, "PB #2 done, bar retracting"),
    (42, "lids dropping on"),
    (46, "finished row + crimp sparkle"),
    (51, "batch rides the belt off the front edge"),
]

def gif_frames(path):
    im = Image.open(path)
    out = []
    try:
        while True:
            out.append(im.convert("RGB").copy())
            im.seek(im.tell() + 1)
    except EOFError:
        pass
    return out

def main():
    frames = gif_frames(GIF)
    w, h = frames[0].size
    if h != 32 or w > 192:
        sys.exit(f"GIF is {w}x{h}; private apps must be <=192 wide and exactly 32 tall")
    FRAMES_DIR.mkdir(parents=True, exist_ok=True)
    for old in FRAMES_DIR.glob("k*.png"):
        old.unlink()
    b64, notes = [], []
    for n, (idx, note) in enumerate(KEYFRAMES):
        if idx >= len(frames):
            sys.exit(f"keyframe {idx} is past the GIF's {len(frames)} frames")
        png = io.BytesIO()
        frames[idx].save(png, format="PNG", optimize=True)
        data = png.getvalue()
        (FRAMES_DIR / f"k{n:02d}.png").write_bytes(data)
        b64.append(base64.b64encode(data).decode("ascii"))
        notes.append(f"  // k{n:02d}  gif frame {idx:2d}  {note}")

    table = ",\n".join(f'  "{s}"' for s in b64)
    js = f'''// Uncrustables assembly line - Glance SCROLL private app ({w}x{h} PNG).
//
// GENERATED by build_worker.py from uncrustables-line.gif - edit that script
// (or the GIF), not this file. Deploy this folder to Cloudflare Pages and paste
// the URL into Glance Setup > Apps > Private Apps with the refresh interval set
// to STEP seconds. Each refresh the panel gets the next keyframe, so the line
// advances one beat per refresh and loops every {len(KEYFRAMES)} beats.
//
// Query params (handy for testing in a browser):
//   ?frame=N   force keyframe N (0-{len(KEYFRAMES) - 1})
//   ?step=S    seconds per beat (default STEP); must match the Glance refresh
//   /preview   an HTML page showing every keyframe, scaled up
//
{chr(10).join(notes)}

const STEP = 60;   // seconds per keyframe = the refresh interval set in Glance Setup
const WIDTH = {w};
const HEIGHT = {h};

const FRAMES = [
{table}
];

function pngBytes(b64) {{
  const bin = atob(b64);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}}

function frameIndex(url, nowMs) {{
  const n = FRAMES.length;
  const forced = url.searchParams.get("frame");
  if (forced !== null && forced !== "") {{
    const f = parseInt(forced, 10) || 0;
    return ((f % n) + n) % n;
  }}
  const step = Math.max(1, parseInt(url.searchParams.get("step"), 10) || STEP);
  return Math.floor(nowMs / 1000 / step) % n;
}}

function preview() {{
  const imgs = FRAMES.map((_, i) =>
    `<figure><img src="/?frame=${{i}}" width="${{WIDTH * 4}}" height="${{HEIGHT * 4}}" alt="keyframe ${{i}}"><figcaption>k${{String(i).padStart(2, "0")}}</figcaption></figure>`
  ).join("");
  const html = `<!doctype html><meta charset="utf-8"><title>Uncrustables line keyframes</title>
<style>body{{background:#111;color:#ccc;font:14px system-ui;margin:24px}}img{{image-rendering:pixelated;display:block;background:#000}}figure{{margin:0 0 14px}}figcaption{{margin-top:2px;color:#888}}</style>
<h1 style="font-size:16px">Uncrustables line - ${{FRAMES.length}} keyframes, one per ${{STEP}} s refresh</h1>
<p>Live frame right now: <img src="/" width="${{WIDTH * 4}}" height="${{HEIGHT * 4}}" alt="live"></p>${{imgs}}`;
  return new Response(html, {{ headers: {{ "Content-Type": "text/html; charset=utf-8", "Cache-Control": "no-store" }} }});
}}

export default {{
  async fetch(request) {{
    const url = new URL(request.url);
    if (url.pathname === "/preview") return preview();
    const idx = frameIndex(url, Date.now());
    return new Response(pngBytes(FRAMES[idx]), {{
      headers: {{
        "Content-Type": "image/png",
        "Content-Length": String(pngBytes(FRAMES[idx]).length),
        "Cache-Control": "no-store, no-cache, max-age=0",
        "X-Frame-Index": String(idx),
      }},
    }});
  }},
}};
'''
    (WORKER_DIR / "_worker.js").write_text(js)
    total = sum(len(s) for s in b64)
    print(f"{len(KEYFRAMES)} keyframes from {GIF.name} ({len(frames)} frames) -> {FRAMES_DIR}")
    print(f"wrote {WORKER_DIR / '_worker.js'} ({total // 1024} KB of embedded PNG)")

if __name__ == "__main__":
    main()
